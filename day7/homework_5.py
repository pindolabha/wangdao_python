#5、	列表、元组，字典的相同点，不同点有哪些，请罗列

#相同点
#1. 都是Python内置的数据结构，用于存储和组织数据。
#2. 都可以包含不同类型的元素，如整数、字符串、列表等。
#3. 都支持迭代，可以使用for循环遍历其中的元素。
#4. 都可以使用索引访问元素，列表和元组支持整数索引，字典支持键索引。
#5. 都可以使用内置函数进行操作，如len()、min()、max()等。


#不同点
#1. 列表是可变的，可以修改、添加和删除元素；元组是不可变的，一旦创建就不能修改；
# 字典是可变的，可以修改
#2. 列表使用方括号[]定义，元组使用圆括号()定义，字典使用花括号{}定义。
#3. 列表和元组是有序的，元素的顺序是固定的；字典是无序的，元素的顺序不固定。
#4. 列表和元组使用整数索引访问元素；字典使用键索引访问元素。
#5. 列表和元组可以包含重复的元素；字典中的键必须是唯一的，值可以重复。