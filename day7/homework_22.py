#22、	若 a = [1,2,3]，令 b = a，执行 b[0] = 9， a[0]亦被改变。为何？
# 如何避免？----讲了深COPY和浅COPY再做

a = [1, 2, 3]
b = a  # b 是 a 的引用，指向同一个列表对象
b[0] = 9  # 修改 b 的第一个元素
print(a)  # 输出结果：[9, 2, 3]，a 的第一个元素也被修改了，因为 a 和 b 指向同一个列表对象
# 避免这种情况的方法是使用列表的 copy() 方法或使用切片来创建一个新的列表对象：
a = [1, 2, 3]
b = a.copy()  # 创建 a 的一个副本，b 指向一个新的列表对象
b[0] = 9  # 修改 b 的第一个元素
print(a)  # 输出结果：[1, 2, 3]，a 的第一个元素没有被修改，因为 a 和 b 指向不同的列表对象
