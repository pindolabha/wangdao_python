#29、	判断 David 和 Alice 是否在字典 {‘Alice’: 20, ‘Beth’: 18, ‘Cecil’: 21} 中。

mydict = {'Alice': 20, 'Beth': 18, 'Cecil': 21}
is_david_in_dict = 'David' in mydict
is_alice_in_dict = 'Alice' in mydict
print(f"David 在字典中: {is_david_in_dict}")  # 输出结果：David 在字典中: False
print(f"Alice 在字典中: {is_alice_in_dict}")  # 输出